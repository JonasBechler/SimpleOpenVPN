#!/usr/bin/env bash
# vpn-dns-update - regenerate the private-zone hosts file for dnsmasq and reload it.
#
# Names per client (host octet N, zone $VPN_DOMAIN, default "internal"):
#   NAME.udp.internal -> 10.8.0.N   always
#   NAME.tcp.internal -> 10.8.1.N   always
#   NAME.internal     -> the address(es) of the instance(s) NAME is connected to
#                        right now; both addresses when it is offline
# The server itself is server.internal / server.udp.internal / server.tcp.internal.
#
# Called by add/revoke scripts and by openvpn-dns.path whenever a client
# connects or disconnects (state files in /run/openvpn-dns/state/<instance>/).
set -euo pipefail
# shellcheck disable=SC1091
source /etc/openvpn/vpn.env

STATE=/run/openvpn-dns/state
HOSTS=/etc/openvpn/dns/hosts
D=${VPN_DOMAIN:-internal}
p_udp=${UDP_NET%.*}
p_tcp=${TCP_NET%.*}
tmp=$(mktemp)

{
  echo "# generated by vpn-dns-update $(date -u +%FT%TZ); do not edit"
  echo "$p_udp.1 server.$D server.udp.$D"
  echo "$p_tcp.1 server.$D server.tcp.$D"
  awk -F, 'NR>1 && $6=="active"' "$CLIENTS_CSV" | while IFS=, read -r name _ udp_ip tcp_ip _ _; do
    on_udp=0; on_tcp=0
    [[ -e $STATE/udp/$name ]]    && on_udp=1
    [[ -e $STATE/tcp443/$name ]] && on_tcp=1
    if (( on_udp == 0 && on_tcp == 0 )); then on_udp=1; on_tcp=1; fi   # offline: static fallback
    line_udp="$udp_ip $name.udp.$D"; line_tcp="$tcp_ip $name.tcp.$D"
    (( on_udp )) && line_udp="$udp_ip $name.$D $name.udp.$D"
    (( on_tcp )) && line_tcp="$tcp_ip $name.$D $name.tcp.$D"
    echo "$line_udp"; echo "$line_tcp"
  done
} > "$tmp"

mkdir -p "$(dirname "$HOSTS")"
if ! cmp -s "$tmp" "$HOSTS" 2>/dev/null; then
  install -m 644 "$tmp" "$HOSTS"
  systemctl is-active --quiet dnsmasq && systemctl reload dnsmasq
fi
rm -f "$tmp"
